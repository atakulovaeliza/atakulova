// задание 3: четные числа 
//здесь for перебирает числа от 1 до 20,а i % 2 != 0  проверяет нечетное ли число
// а continue он пропускает нечтное число, print (i) он выводит четные числа

void main () {
  for (int i = 1; i <= 20; i++){
    if (i % 2 != 0){
      continue;
      
    }
    print(i);
  }
}