// задание 4: сейф
// программа будет просить пароль,если я введу пароль не правильно, программа попросит еще раз
// и пока я не введу он будет еще и  еще спрашивать пока я ре введу правильный пароль
import 'dart:io';

void main (){
  String pin;

  do {
    print ("Введите Pin-код: ");
    pin = stdin.readLineSync()!;
  }
  while (pin != "1234");

  print ("сейф открыт!");
}